static int check(const char *name, const float *u, const float *th_ref)
{
    float th[PARAMNET_THETA_DIM];
    float maxerr = 0.0f;
    int fails = 0;
    paramnet_u_to_theta(u, th);
    for (int i = 0; i < PARAMNET_THETA_DIM; i++) {
        float e = fabsf(th[i] - th_ref[i]);
        if (e > maxerr) maxerr = e;
        if (e > 2e-4f) {
            if (fails < 6)
                printf("  [%s] theta[%d] C=%.6f ref=%.6f err=%.2e\n", name, i, th[i], th_ref[i], e);
            fails++;
        }
    }
    printf("%-6s: maxerr=%.2e  %s\n", name, maxerr, fails ? "FAIL" : "OK");
    return fails;
}

/* θ → blob 字节级核对（gamma_on=1, gamma_strength=1.0，与 golden 生成参数一致）。 */
static int check_blob(const char *name, const float *th, const unsigned char *ref, size_t ref_len)
{
    unsigned char buf[PARAMNET_BLOB_MAX];
    size_t n = paramnet_theta_to_blob(th, 1, 1, 1, 1.0f, buf, sizeof(buf));
    int fails = 0;
    if (n != ref_len) {
        printf("%-6s blob: len %zu != %zu FAIL\n", name, n, ref_len);
        return 1;
    }
    for (size_t i = 0; i < n; i++) {
        if (buf[i] != ref[i]) {
            if (fails < 8)
                printf("  [%s] blob[%zu] C=%u ref=%u\n", name, i, buf[i], ref[i]);
            fails++;
        }
    }
    printf("%-6s blob: %zu bytes  %s\n", name, n, fails ? "FAIL" : "OK");
    return fails;
}

int main(void)
{
    int fails = 0;
    fails += check("zeros", U_ZEROS, TH_ZEROS);
    fails += check("ones", U_ONES, TH_ONES);
    fails += check("mix", U_MIX, TH_MIX);
    fails += check_blob("zeros", TH_ZEROS, BLOB_ZEROS, sizeof(BLOB_ZEROS));
    fails += check_blob("ones", TH_ONES, BLOB_ONES, sizeof(BLOB_ONES));
    fails += check_blob("mix", TH_MIX, BLOB_MIX, sizeof(BLOB_MIX));
    if (fails) {
        printf("test_paramnet_map: %d mismatch(es) — C u_to_theta 与 Python 不一致\n", fails);
        return 1;
    }
    printf("test_paramnet_map: all OK (C u_to_theta == Python golden)\n");
    return 0;
}
